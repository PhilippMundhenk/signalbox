"""Rewrite the expected snapshot of every committed recording after a model or adapter change.

A recording (tests/fixtures/recordings/*.json) holds the device's answers and the snapshot they
must give. When a model field is added or an adapter reads more, the expected snapshot changes;
this replays every recording and stores what it gives now. Review the diff before committing:
the snapshot is the expectation of the regression test.

    python tools/regen_recordings.py
"""

from __future__ import annotations

import asyncio
import json
import sys
from pathlib import Path
from typing import Any

from signalbox.recording import load, replay_snapshot, stable
from signalbox.sim.snmp import SnmprecTransport, adapter_for, typical_switch

ROOT = Path(__file__).resolve().parents[1]


async def snmp_snapshot(path: Path) -> Any:
    adapter = adapter_for(SnmprecTransport.from_file(path))
    try:
        return stable(await adapter.observe())
    finally:
        await adapter.close()


def regen_snmp() -> None:
    """The ``.snmprec`` recordings of tests/fixtures/snmp and the snapshots the ``snmp``
    adapter must make of them (the typical switch is generated by the simulator)."""
    folder = ROOT / "tests" / "fixtures" / "snmp"
    (folder / "managed-switch.snmprec").write_text(typical_switch(), encoding="utf-8")
    for path in sorted(folder.glob("*.snmprec")):
        out = path.with_suffix(".snapshot.json")
        out.write_text(
            json.dumps(asyncio.run(snmp_snapshot(path)), indent=1, ensure_ascii=False) + "\n"
        )
        print(f"wrote {out.relative_to(ROOT)}")


def main() -> int:
    regen_snmp()
    for path in sorted((ROOT / "tests" / "fixtures" / "recordings").glob("*.json")):
        raw = json.loads(path.read_text())
        snapshot, unmatched = asyncio.run(replay_snapshot(load(path)))
        if unmatched:
            print(f"{path.name}: calls without a recorded answer: {unmatched}", file=sys.stderr)
            return 1
        raw["snapshot"] = snapshot
        path.write_text(json.dumps(raw, indent=1, ensure_ascii=False) + "\n")
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
